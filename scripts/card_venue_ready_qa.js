const assert=require('node:assert/strict'),fs=require('node:fs');
const gate=require('../server/card_venue_ready'),engine=require('../server/engine');
let checks=0;function check(fn){fn();checks++;}
const room={state:engine.createInitialState(6)};
room.state.players.forEach((p,i)=>p.isCPU=i===5);
const first=gate.begin(room),payload={id:first.id,roundNo:first.roundNo};
check(()=>assert.deepEqual(first.required,[0,1,2,3,4]));
check(()=>assert.equal(gate.waiting(room),true));
check(()=>assert.equal(gate.acknowledge(room,0,{...payload,id:'stale'}),false));
check(()=>assert.equal(gate.acknowledge(room,5,payload),false));
for(let i=0;i<4;i++)gate.acknowledge(room,i,payload);
check(()=>assert.equal(gate.waiting(room),true));
gate.acknowledge(room,0,payload);
check(()=>assert.equal(gate.view(room).ready.length,4));
room.state.players[4].offline=true;
check(()=>assert.equal(gate.waiting(room),true));
room.state.players[4].offline=false;gate.acknowledge(room,4,payload);
check(()=>assert.equal(gate.waiting(room),false));
const snapshot=JSON.stringify(room.state);gate.view(room);
check(()=>assert.equal(JSON.stringify(room.state),snapshot));
room.state.roundNo++;const second=gate.begin(room);
check(()=>assert.notEqual(second.id,first.id));
check(()=>assert.deepEqual(second.ready,[]));
check(()=>assert.equal(gate.acknowledge(room,0,payload),false));
for(let i=0;i<4;i++)gate.acknowledge(room,i,{id:second.id,roundNo:second.roundNo});
room.state.players[4].isCPU=true;
check(()=>assert.equal(gate.waiting(room),false));
room.state.players[4].isCPU=false;
check(()=>assert.equal(gate.waiting(room),false));
room.state.players.forEach(p=>p.isCPU=true);gate.begin(room);
check(()=>assert.equal(gate.waiting(room),false));
check(()=>assert.deepEqual(Object.keys(gate.view(room)).sort(),['id','ready','required','roundNo','waiting']));
const html=fs.readFileSync(require('node:path').join(__dirname,'../public/game.html'),'utf8');
check(()=>assert.ok(html.includes(fs.readFileSync(require('node:path').join(__dirname,'card_venue_ready_client.js'),'utf8'))));
console.log(JSON.stringify({passed:true,checks,scope:'Room barrier: six seats, CPU, stale/duplicate confirmations, offline grace, takeover, next-round reset, no save/private fields and exact embedded client'}));
